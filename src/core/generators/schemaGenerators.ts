import type { TSType } from '@/core/converters';
import { inferFromArray, capitalize } from '@/core/converters';
import * as yaml from 'js-yaml';

// ── JSON Schema Draft 2020-12 Generator ──────────────────────────────────────

interface JSONSchemaNode {
  $schema?: string;
  title?: string;
  type?: string | string[];
  format?: string;
  properties?: Record<string, JSONSchemaNode>;
  required?: string[];
  items?: JSONSchemaNode;
  anyOf?: JSONSchemaNode[];
  additionalProperties?: boolean;
}

function tsTypeToJsonSchema(t: TSType, title?: string): JSONSchemaNode {
  switch (t.kind) {
    case 'string':
      if (t.format === 'email') return { type: 'string', format: 'email' };
      if (t.format === 'url') return { type: 'string', format: 'uri' };
      if (t.format === 'datetime') return { type: 'string', format: 'date-time' };
      return { type: 'string' };

    case 'number':
      return { type: t.isInteger ? 'integer' : 'number' };

    case 'boolean':
      return { type: 'boolean' };

    case 'null':
      return { type: 'null' };

    case 'unknown':
      return {};

    case 'array':
      return {
        type: 'array',
        items: tsTypeToJsonSchema(t.element),
      };

    case 'union':
      return {
        anyOf: t.members.map((m) => tsTypeToJsonSchema(m)),
      };

    case 'object': {
      const properties: Record<string, JSONSchemaNode> = {};
      const required: string[] = [];

      for (const [key, field] of t.fields) {
        properties[key] = tsTypeToJsonSchema(field.type, capitalize(key));
        if (!field.optional) {
          required.push(key);
        }
      }

      const node: JSONSchemaNode = {
        type: 'object',
        properties,
        additionalProperties: false,
      };

      if (title) node.title = title;
      if (required.length > 0) node.required = required;
      return node;
    }
  }
}

export function toJSONSchema(data: unknown): string {
  const records = Array.isArray(data) ? data : [data];
  const rootType = inferFromArray(records);
  const rootSchema = tsTypeToJsonSchema(rootType, 'DataModel');

  const fullSchema: JSONSchemaNode = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'FormatPulseGeneratedSchema',
    ...rootSchema,
  };

  return JSON.stringify(fullSchema, null, 2);
}

// ── OpenAPI 3.1 Spec Component Generator ──────────────────────────────────────

export function toOpenAPI(data: unknown): string {
  const records = Array.isArray(data) ? data : [data];
  const rootType = inferFromArray(records);
  const schemaNode = tsTypeToJsonSchema(rootType);

  const openApiDoc = {
    openapi: '3.1.0',
    info: {
      title: 'FormatPulse Data Contract API',
      version: '1.0.0',
      description: 'Auto-generated OpenAPI 3.1 schema definition from client-side payload inference.',
    },
    components: {
      schemas: {
        DataModel: schemaNode,
      },
    },
  };

  const yamlContent = yaml.dump(openApiDoc, { indent: 2, lineWidth: 100, noRefs: true });
  return `# Generated by FormatPulse — OpenAPI 3.1 Spec Generator\n# 100% Client-Side Contract Inference\n\n${yamlContent}`;
}

// ── Prisma Schema Generator ──────────────────────────────────────────────────

function prismaType(t: TSType): string {
  switch (t.kind) {
    case 'string':
      if (t.format === 'datetime') return 'DateTime';
      return 'String';
    case 'number':
      return t.isInteger ? 'Int' : 'Float';
    case 'boolean':
      return 'Boolean';
    case 'null':
    case 'unknown':
      return 'String';
    case 'array':
      return `${prismaType(t.element)}[]`;
    case 'union':
      return 'Json';
    case 'object':
      return 'Json';
  }
}

export function toPrisma(data: unknown): string {
  const records = Array.isArray(data) ? data : [data];
  const rootType = inferFromArray(records);

  if (rootType.kind !== 'object') {
    return '// Prisma Schema requires an object structure to map models.';
  }

  const lines: string[] = [
    '// Generated by FormatPulse — Prisma Schema Generator',
    '// Paste into your schema.prisma file',
    '',
    'datasource db {',
    '  provider = "postgresql"',
    '  url      = env("DATABASE_URL")',
    '}',
    '',
    'generator client {',
    '  provider = "prisma-client-js"',
    '}',
    '',
    'model DataModel {',
  ];

  let hasId = false;

  for (const [key, field] of rootType.fields) {
    const isIdField = key.toLowerCase() === 'id' || key.toLowerCase() === 'uuid';
    if (isIdField) hasId = true;

    let pType = prismaType(field.type);
    if (field.optional && !pType.endsWith('[]')) {
      pType += '?';
    }

    let directives = '';
    if (isIdField) {
      if (pType.startsWith('Int')) {
        directives = ' @id @default(autoincrement())';
      } else {
        directives = ' @id @default(uuid())';
      }
    } else if (key.toLowerCase() === 'created_at' || key.toLowerCase() === 'createdat') {
      directives = ' @default(now())';
    } else if (key.toLowerCase() === 'updated_at' || key.toLowerCase() === 'updatedat') {
      directives = ' @updatedAt';
    } else if (key.toLowerCase() === 'email') {
      directives = ' @unique';
    }

    // Format column alignment
    const colName = /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(key) ? key : `"${key}"`;
    lines.push(`  ${colName.padEnd(16)} ${pType}${directives}`);
  }

  if (!hasId) {
    // Inject synthetic primary key at top
    lines.splice(13, 0, '  id               String   @id @default(uuid())');
  }

  lines.push('}');
  return lines.join('\n');
}

// ── Python Pydantic v2 Generator ─────────────────────────────────────────────

function pydanticType(t: TSType, nestedName?: string): string {
  switch (t.kind) {
    case 'string':
      if (t.format === 'email') return 'EmailStr';
      if (t.format === 'url') return 'HttpUrl';
      if (t.format === 'datetime') return 'datetime';
      return 'str';
    case 'number':
      return t.isInteger ? 'int' : 'float';
    case 'boolean':
      return 'bool';
    case 'null':
      return 'None';
    case 'unknown':
      return 'Any';
    case 'array':
      return `List[${pydanticType(t.element)}]`;
    case 'union':
      return `Union[${t.members.map((m) => pydanticType(m)).join(', ')}]`;
    case 'object':
      return nestedName ?? 'Dict[str, Any]';
  }
}

export function toPydantic(data: unknown): string {
  const records = Array.isArray(data) ? data : [data];
  const rootType = inferFromArray(records);

  const models: string[] = [];

  function emitModel(name: string, type: TSType): string {
    if (type.kind !== 'object') return pydanticType(type);

    const lines: string[] = [];
    lines.push(`class ${name}(BaseModel):`);

    let fieldCount = 0;
    for (const [key, field] of type.fields) {
      fieldCount++;
      const safeKey = /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(key) ? key : `field_${key.replace(/[^a-zA-Z0-9_]/g, '_')}`;
      let fieldType: string;

      if (field.type.kind === 'object') {
        const subName = capitalize(key) + 'Model';
        fieldType = emitModel(subName, field.type);
      } else if (field.type.kind === 'array' && field.type.element.kind === 'object') {
        const subName = capitalize(key) + 'Item';
        const itemType = emitModel(subName, field.type.element);
        fieldType = `List[${itemType}]`;
      } else {
        fieldType = pydanticType(field.type);
      }

      if (field.optional) {
        lines.push(`    ${safeKey}: Optional[${fieldType}] = None`);
      } else {
        lines.push(`    ${safeKey}: ${fieldType}`);
      }
    }

    if (fieldCount === 0) {
      lines.push('    pass');
    }

    models.push(lines.join('\n'));
    return name;
  }

  emitModel('DataModel', rootType);

  const header = [
    '# Generated by FormatPulse — Python Pydantic v2 Model Generator',
    'from __future__ import annotations',
    'from datetime import datetime',
    'from typing import Optional, List, Dict, Any, Union',
    'from pydantic import BaseModel, EmailStr, HttpUrl',
    '',
  ].join('\n');

  return `${header}\n${models.join('\n\n')}`;
}

// ── Rust Serde Struct Generator ───────────────────────────────────────────────

function rustType(t: TSType, nestedName?: string): string {
  switch (t.kind) {
    case 'string':
      return 'String';
    case 'number':
      return t.isInteger ? 'i64' : 'f64';
    case 'boolean':
      return 'bool';
    case 'null':
    case 'unknown':
      return 'serde_json::Value';
    case 'array':
      return `Vec<${rustType(t.element)}>`;
    case 'union':
      return 'serde_json::Value';
    case 'object':
      return nestedName ?? 'serde_json::Value';
  }
}

function toSnakeCase(s: string): string {
  return s
    .replace(/([A-Z])/g, '_$1')
    .toLowerCase()
    .replace(/^_/, '')
    .replace(/[^a-z0-9_]/g, '_');
}

export function toRustSerde(data: unknown): string {
  const records = Array.isArray(data) ? data : [data];
  const rootType = inferFromArray(records);

  const structs: string[] = [];

  function emitStruct(name: string, type: TSType): string {
    if (type.kind !== 'object') return rustType(type);

    const lines: string[] = [];
    lines.push('#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]');
    lines.push(`pub struct ${name} {`);

    for (const [key, field] of type.fields) {
      const fieldIdent = toSnakeCase(key);
      let rType: string;

      if (field.type.kind === 'object') {
        const subName = capitalize(key);
        rType = emitStruct(subName, field.type);
      } else if (field.type.kind === 'array' && field.type.element.kind === 'object') {
        const subName = capitalize(key) + 'Item';
        const itemType = emitStruct(subName, field.type.element);
        rType = `Vec<${itemType}>`;
      } else {
        rType = rustType(field.type);
      }

      if (field.optional) {
        lines.push(`    #[serde(skip_serializing_if = "Option::is_none")]`);
        if (fieldIdent !== key) {
          lines.push(`    #[serde(rename = "${key}")]`);
        }
        lines.push(`    pub ${fieldIdent}: Option<${rType}>,`);
      } else {
        if (fieldIdent !== key) {
          lines.push(`    #[serde(rename = "${key}")]`);
        }
        lines.push(`    pub ${fieldIdent}: ${rType},`);
      }
    }

    lines.push('}');
    structs.push(lines.join('\n'));
    return name;
  }

  emitStruct('DataModel', rootType);

  const header = [
    '// Generated by FormatPulse — Rust Serde Struct Generator',
    'use serde::{Deserialize, Serialize};',
    '',
  ].join('\n');

  return `${header}\n${structs.join('\n\n')}`;
}

// ── Go Struct Generator ───────────────────────────────────────────────────────

function goType(t: TSType, nestedName?: string): string {
  switch (t.kind) {
    case 'string':
      if (t.format === 'datetime') return 'time.Time';
      return 'string';
    case 'number':
      return t.isInteger ? 'int64' : 'float64';
    case 'boolean':
      return 'bool';
    case 'null':
    case 'unknown':
      return 'any';
    case 'array':
      return `[]${goType(t.element)}`;
    case 'union':
      return 'any';
    case 'object':
      return nestedName ?? 'map[string]any';
  }
}

function toGoFieldName(s: string): string {
  const parts = s.split(/[^a-zA-Z0-9]/).filter(Boolean);
  if (parts.length === 0) return 'Field';
  return parts
    .map((p) => {
      const upper = p.toUpperCase();
      if (upper === 'ID' || upper === 'URL' || upper === 'API' || upper === 'IP' || upper === 'UUID') {
        return upper;
      }
      return p.charAt(0).toUpperCase() + p.slice(1);
    })
    .join('');
}

export function toGoStruct(data: unknown): string {
  const records = Array.isArray(data) ? data : [data];
  const rootType = inferFromArray(records);

  const structs: string[] = [];
  let needsTime = false;

  function emitStruct(name: string, type: TSType): string {
    if (type.kind !== 'object') return goType(type);

    const lines: string[] = [];
    lines.push(`type ${name} struct {`);

    for (const [key, field] of type.fields) {
      const goField = toGoFieldName(key);
      let gType: string;

      if (field.type.kind === 'object') {
        const subName = capitalize(key);
        gType = emitStruct(subName, field.type);
      } else if (field.type.kind === 'array' && field.type.element.kind === 'object') {
        const subName = capitalize(key) + 'Item';
        const itemType = emitStruct(subName, field.type.element);
        gType = `[]${itemType}`;
      } else {
        if (field.type.kind === 'string' && field.type.format === 'datetime') {
          needsTime = true;
        }
        gType = goType(field.type);
      }

      if (field.optional) {
        if (gType === 'time.Time') {
          lines.push(`\t${goField.padEnd(16)} *${gType} \`json:"${key},omitempty"\``);
        } else {
          lines.push(`\t${goField.padEnd(16)} *${gType} \`json:"${key},omitempty"\``);
        }
      } else {
        lines.push(`\t${goField.padEnd(16)} ${gType} \`json:"${key}"\``);
      }
    }

    lines.push('}');
    structs.push(lines.join('\n'));
    return name;
  }

  emitStruct('DataModel', rootType);

  const imports = needsTime ? 'import (\n\t"time"\n)\n\n' : '';

  const header = [
    '// Generated by FormatPulse — Go Struct Generator',
    'package models',
    '',
    imports,
  ].join('\n');

  return `${header}${structs.join('\n\n')}`;
}
